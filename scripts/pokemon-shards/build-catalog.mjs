// Builds the validated shard catalog from public PokéAPI species metadata.
//   node scripts/pokemon-shards/build-catalog.mjs --input-dir DIR [--fetch]
//     [--output src/pages/QuizPage/shards/catalog.json]
//     [--sql-output supabase/seed/pokemon_shards_v1.sql]
// Downloaded data is parsed as JSON only, never executed. Any missing or
// invalid entry fails the whole build; no partial catalog is ever written.
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { getPokemonPower } from '../../src/pages/PokemonPage/power.mjs'

export const CATALOG_VERSION = 1
export const TOTAL = 1025
const API = 'https://pokeapi.co/api/v2/'
const STATS = [
  'hp',
  'attack',
  'defense',
  'special-attack',
  'special-defense',
  'speed',
]
const range = (n) => Array.from({ length: n }, (_, i) => i + 1)

const fail = (msg) => {
  throw new Error(`catalog: ${msg}`)
}
const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v)
const text = (v, label) =>
  typeof v === 'string' && v ? v : fail(`${label} must be a non-empty string`)

export function buildCatalog(data, { ids = range(TOTAL) } = {}) {
  const extra = Object.keys(data).filter(
    (k) => k !== 'species' && k !== 'pokemon'
  )
  if (extra.length) fail(`unexpected data key ${extra.join(',')}`)
  const wanted = new Set(ids)
  for (const key of ['species', 'pokemon'])
    for (const id of data[key].keys())
      if (!wanted.has(id)) fail(`unexpected ${key} ${id}`)

  const species = [...ids]
    .sort((a, b) => a - b)
    .map((id) => {
      const s = data.species.get(id) ?? fail(`missing species ${id}`)
      const p =
        data.pokemon.get(id) ?? fail(`missing pokemon ${id} (default form)`)
      if (!isObj(s) || !isObj(p)) fail(`species/pokemon ${id} malformed`)
      if (s.id !== id || p.id !== id) fail(`id mismatch for ${id}`)
      const name = text(s.name, `species ${id} name`)
      const def =
        Array.isArray(s.varieties) && s.varieties.filter((v) => v?.is_default)
      if (!def || def.length !== 1)
        fail(`species ${id} needs exactly one default form`)
      if (def[0].pokemon?.name !== p.name || p.is_default === false)
        fail(`pokemon ${id} is not the default form of species ${id}`)
      if (p.species && p.species.name !== name)
        fail(`pokemon ${id} species name mismatch`)
      const captureRate = s.capture_rate
      if (
        !Number.isInteger(captureRate) ||
        captureRate < 1 ||
        captureRate > 255
      )
        fail(`species ${id} capture_rate must be an integer 1..255`)
      if (typeof s.is_legendary !== 'boolean')
        fail(`species ${id} is_legendary must be boolean`)
      if (typeof s.is_mythical !== 'boolean')
        fail(`species ${id} is_mythical must be boolean`)
      if (!Array.isArray(p.stats) || p.stats.length !== 6)
        fail(`pokemon ${id} needs six stats`)
      const stats = p.stats.map((e, i) => {
        if (e?.stat?.name !== STATS[i])
          fail(`pokemon ${id} stat ${i} must be ${STATS[i]}`)
        const v = e.base_stat
        if (!Number.isInteger(v) || v < 0 || v > 255)
          fail(`pokemon ${id} stat ${STATS[i]} invalid`)
        return v
      })
      if (!Array.isArray(p.types) || p.types.length < 1 || p.types.length > 2)
        fail(`pokemon ${id} types must have 1-2 entries`)
      const types = [...p.types]
        .sort((a, b) => a?.slot - b?.slot)
        .map((t) => text(t?.type?.name, `pokemon ${id} type`))
      const { level } = getPokemonPower(
        stats.map((base_stat) => ({ base_stat }))
      )
      return {
        id,
        name,
        types,
        captureRate,
        legendary: s.is_legendary,
        mythical: s.is_mythical,
        stats,
        powerLevel: level,
      }
    })
  return { version: CATALOG_VERSION, species }
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`

export function renderSeedSql(catalog) {
  const rows = catalog.species.map((s) => {
    const meta = JSON.stringify({
      name: s.name,
      types: s.types,
      captureRate: s.captureRate,
      legendary: s.legendary,
      mythical: s.mythical,
      stats: s.stats,
      powerLevel: s.powerLevel,
    })
    return `  (${Number(catalog.version)}, ${Number(s.id)}, ${q(meta)}::jsonb)`
  })
  return [
    '-- Generated by scripts/pokemon-shards/build-catalog.mjs. Do not edit.',
    'begin;',
    'insert into public.pokemon_shard_catalog (version, pokemon_id, metadata) values',
    rows.join(',\n'),
    'on conflict (version, pokemon_id) do nothing;',
    'commit;',
    '',
  ].join('\n')
}

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'))

export function loadDir(dir) {
  const data = { species: new Map(), pokemon: new Map() }
  for (const key of ['species', 'pokemon']) {
    const folder = path.join(dir, key)
    if (!fs.existsSync(folder)) fail(`missing directory ${folder}`)
    for (const file of fs.readdirSync(folder).sort()) {
      if (!/^\d+\.json$/.test(file)) continue
      const id = Number(file.slice(0, -5))
      const json = readJson(path.join(folder, file))
      if (json?.id !== id) fail(`${key}/${file} holds id ${json?.id}`)
      data[key].set(id, json)
    }
  }
  return data
}

const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex')

async function getJson(url) {
  if (!url.startsWith(API)) fail(`refusing non-PokéAPI url ${url}`)
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url)
      if (!res.ok) throw new Error(`${res.status}`)
      return await res.json()
    } catch (err) {
      if (attempt === 4) fail(`cannot fetch ${url}: ${err.message}`)
      await new Promise((r) => setTimeout(r, 500 * attempt))
    }
  }
}

export async function fetchDir(dir, ids = range(TOTAL)) {
  for (const key of ['species', 'pokemon'])
    fs.mkdirSync(path.join(dir, key), { recursive: true })
  const files = {}
  const write = (rel, obj) => {
    const body = JSON.stringify(obj, null, 1) + '\n'
    fs.writeFileSync(path.join(dir, rel), body)
    files[rel] = sha(body)
  }
  const queue = [...ids]
  const work = async () => {
    for (let id; (id = queue.shift()) !== undefined;) {
      const s = await getJson(`${API}pokemon-species/${id}/`)
      const def = (s.varieties ?? []).filter((v) => v.is_default)
      if (def.length !== 1) fail(`species ${id} needs exactly one default form`)
      const p = await getJson(def[0].pokemon.url)
      write(`species/${id}.json`, {
        id: s.id,
        name: s.name,
        capture_rate: s.capture_rate,
        is_legendary: s.is_legendary,
        is_mythical: s.is_mythical,
        varieties: s.varieties.map((v) => ({
          is_default: v.is_default,
          pokemon: { name: v.pokemon.name },
        })),
      })
      write(`pokemon/${id}.json`, {
        id: p.id,
        name: p.name,
        is_default: p.is_default,
        species: { name: p.species?.name },
        types: p.types,
        stats: p.stats.map((e) => ({
          base_stat: e.base_stat,
          stat: { name: e.stat.name },
        })),
      })
    }
  }
  await Promise.all(Array.from({ length: 6 }, work))
  return files
}

const sorted = (o) =>
  Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : 1)))

async function main(argv) {
  const arg = (name) => {
    const i = argv.indexOf(`--${name}`)
    return i < 0 ? undefined : argv[i + 1]
  }
  const dir = arg('input-dir') ?? fail('--input-dir required')
  const root = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    '../..'
  )
  const output =
    arg('output') ?? path.join(root, 'src/pages/QuizPage/shards/catalog.json')
  const sqlOutput =
    arg('sql-output') ?? path.join(root, 'supabase/seed/pokemon_shards_v1.sql')
  let fetched
  if (argv.includes('--fetch')) fetched = await fetchDir(dir)
  const catalog = buildCatalog(loadDir(dir))
  const json = JSON.stringify(catalog, null, 1) + '\n'
  const sql = renderSeedSql(catalog)
  fs.mkdirSync(path.dirname(output), { recursive: true })
  fs.mkdirSync(path.dirname(sqlOutput), { recursive: true })
  fs.writeFileSync(output, json)
  fs.writeFileSync(sqlOutput, sql)
  const files = fetched ?? {}
  if (!fetched)
    for (const key of ['species', 'pokemon'])
      for (const f of fs
        .readdirSync(path.join(dir, key))
        .filter((n) => n.endsWith('.json')))
        files[`${key}/${f}`] = sha(fs.readFileSync(path.join(dir, key, f)))
  fs.writeFileSync(
    path.join(dir, 'manifest.json'),
    JSON.stringify(
      {
        source: API,
        catalogVersion: catalog.version,
        count: catalog.species.length,
        outputs: { catalog: sha(json), sql: sha(sql) },
        files: sorted(files),
      },
      null,
      1
    ) + '\n'
  )
  console.log(`catalog v${catalog.version}: ${catalog.species.length} species`)
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  main(process.argv.slice(2)).catch((e) => {
    console.error(e.message)
    process.exit(1)
  })
