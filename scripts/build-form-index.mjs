// Builds src/pages/PokemonPage/form-index.mjs: every species with more than
// one variety (Mega, Gigantamax, regional forms), so the page and its
// skeleton can draw the form row before the species arrives. Re-run when
// PokéAPI adds forms:
//   node scripts/build-form-index.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const API = 'https://pokeapi.co/api/v2/'
const idOf = (url) => Number(url.match(/\/(\d+)\/?$/)[1])

const get = async (path) => {
  for (let attempt = 0; ; attempt++) {
    const response = await fetch(new URL(path, API))
    if (response.ok) return response.json()
    if (attempt >= 3) throw new Error(`${path}: HTTP ${response.status}`)
    await new Promise((resolve) => setTimeout(resolve, 500 * (attempt + 1)))
  }
}

const pool = async (items, task, size = 12) => {
  const out = []
  let next = 0
  await Promise.all(
    Array.from({ length: size }, async () => {
      while (next < items.length) {
        const i = next++
        out[i] = await task(items[i])
      }
    })
  )
  return out
}

// the alternate forms (ids past the National Dex) name their species
const { results } = await get('pokemon?limit=100000')
const alternates = results.filter(({ url }) => idOf(url) > 10000)
const speciesNames = new Set(
  await pool(alternates, async ({ url }) => (await get(url)).species.name)
)
const species = await pool([...speciesNames], (name) =>
  get(`pokemon-species/${name}`)
)

// "charizard:6,mega-x:10034,…": a variety outside the species' name
// (pikachu's partner caps aside, there are a few) keeps its whole name
// behind "="
const lines = species
  .filter((entry) => entry.varieties.length > 1)
  .sort((a, b) => a.id - b.id)
  .map(({ name, varieties }) => {
    const parts = varieties.map(({ is_default: isDefault, pokemon }) => {
      const id = idOf(pokemon.url)
      if (isDefault)
        return `${pokemon.name === name ? '' : `=${pokemon.name}`}!${id}`
      const short = pokemon.name.startsWith(`${name}-`)
        ? pokemon.name.slice(name.length + 1)
        : `=${pokemon.name}`
      return `${short}:${id}`
    })
    return `${name}|${parts.join(',')}`
  })

const target = fileURLToPath(
  new URL('../src/pages/PokemonPage/form-index.mjs', import.meta.url)
)
writeFileSync(
  target,
  `// Generated by scripts/build-form-index.mjs — do not edit by hand.
// One species per entry, "name|variety,variety": a variety is its name past
// the species' ("mega-x"), or "=whole-name"; "!id" marks the default.
const DATA =
  '${lines.join(';')}'

let index
let names

const build = () => {
  index = new Map()
  names = new Map()
  for (const line of DATA.split(';')) {
    const [name, list] = line.split('|')
    const varieties = list.split(',').map((part) => {
      const isDefault = part.includes('!')
      const [label, id] = part.split(isDefault ? '!' : ':')
      const full = label.startsWith('=')
        ? label.slice(1)
        : label
          ? \`\${name}-\${label}\`
          : name
      return {
        is_default: isDefault,
        pokemon: { name: full, url: \`/pokemon/\${id}/\` },
        id,
      }
    })
    const id = Number(varieties.find((v) => v.is_default).id)
    const species = {
      id,
      name,
      varieties: varieties.map((variety) => ({
        is_default: variety.is_default,
        pokemon: variety.pokemon,
      })),
    }
    index.set(name, species).set(String(id), species)
    for (const variety of varieties) {
      index.set(variety.pokemon.name, species).set(variety.id, species)
      names.set(variety.pokemon.name, variety.pokemon.name)
      names.set(variety.id, variety.pokemon.name)
      if (variety.is_default) names.set(name, variety.pokemon.name)
    }
  }
}

/**
 * The species (as PokéAPI shapes it: id, name, varieties) of a Pokémon
 * name, species name or id, when it has more than one variety.
 */
export function formSpeciesOf(key) {
  if (!key) return undefined
  if (!index) build()
  return index.get(String(key))
}

/** The variety a key shows: urshifu → urshifu-single-strike, 10034 → charizard-mega-x. */
export function formNameOf(key) {
  if (!key) return undefined
  if (!names) build()
  return names.get(String(key))
}
`
)
console.log(`wrote ${target} (${lines.length} species)`)
