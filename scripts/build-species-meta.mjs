// Builds src/pages/MapPage/data/species-meta.mjs: base stat total, capture
// rate and legendary/mythical/baby flag for every National Dex species, so the
// map's spawn rules need no API call at run time. Re-run when PokéAPI adds species:
//   node scripts/build-species-meta.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const SPECIES = 1025
const get = async (url) => {
  for (let attempt = 0; attempt < 3; attempt++) {
    const response = await fetch(url).catch(() => null)
    if (response?.ok) return response.json()
    await new Promise((r) => setTimeout(r, 400 * (attempt + 1)))
  }
  throw new Error(`failed: ${url}`)
}

const rows = new Array(SPECIES)
let next = 1
const worker = async () => {
  while (next <= SPECIES) {
    const id = next++
    const [species, pokemon] = await Promise.all([
      get(`https://pokeapi.co/api/v2/pokemon-species/${id}`),
      get(`https://pokeapi.co/api/v2/pokemon/${id}`),
    ])
    const bst = pokemon.stats.reduce((sum, s) => sum + s.base_stat, 0)
    // 0 normal, 1 legendary, 2 mythical, 3 baby
    const flag = species.is_mythical ? 2 : species.is_legendary ? 1 : species.is_baby ? 3 : 0
    rows[id - 1] = [bst, species.capture_rate, flag]
  }
}
await Promise.all(Array.from({ length: 12 }, worker))

const target = fileURLToPath(new URL('../src/pages/MapPage/data/species-meta.mjs', import.meta.url))
writeFileSync(
  target,
  `// Generated by scripts/build-species-meta.mjs — do not edit by hand.
// One [bst, capture rate, flag] per National Dex number (#1 first);
// flag: 0 normal, 1 legendary, 2 mythical, 3 baby.
export const META = ${JSON.stringify(rows)}

/** { bst, capture, flag } of a species; null outside 1–${SPECIES}. */
export function metaOf(id) {
  const row = META[Number(id) - 1]
  return row ? { bst: row[0], capture: row[1], flag: row[2] } : null
}
`
)
console.log('wrote', rows.length)
