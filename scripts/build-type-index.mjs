// Builds src/components/pokemon-page/type-index.mjs: every National Dex
// species' types, two characters per Pokémon, so lists can colour cards by
// type without one API call per card. Re-run when PokéAPI adds species:
//   node scripts/build-type-index.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { TYPE_DATA } from '../src/components/pokemon-page/type-data.mjs'

const SPECIES = 1025
const TYPES = Object.keys(TYPE_DATA)
const LETTERS = 'abcdefghijklmnopqr'

const slots = Array.from({ length: SPECIES + 1 }, () => ['.', '.'])
for (const [index, type] of TYPES.entries()) {
  const response = await fetch(`https://pokeapi.co/api/v2/type/${type}`)
  if (!response.ok) throw new Error(`type ${type}: HTTP ${response.status}`)
  const { pokemon } = await response.json()
  for (const { pokemon: mon, slot } of pokemon) {
    const id = Number(mon.url.match(/\/(\d+)\/?$/)[1])
    if (id >= 1 && id <= SPECIES) slots[id][slot - 1] = LETTERS[index]
  }
}

const missing = slots
  .slice(1)
  .flatMap((pair, i) => (pair[0] === '.' ? [i + 1] : []))
if (missing.length) throw new Error(`no primary type for ${missing.join(', ')}`)

const codes = slots
  .slice(1)
  .map((pair) => pair.join(''))
  .join('')
const target = fileURLToPath(
  new URL('../src/components/pokemon-page/type-index.mjs', import.meta.url)
)
writeFileSync(
  target,
  `// Generated by scripts/build-type-index.mjs — do not edit by hand.
// Two characters per National Dex number (#1 first): primary, secondary
// type as a letter of TYPE_ORDER ('.' = none).
import { TYPE_DATA } from './type-data.mjs'

export const TYPE_ORDER = Object.keys(TYPE_DATA)
const LETTERS = '${LETTERS}'
const CODES =
  '${codes}'

/** ['dragon', 'ground'] for 445; [] outside 1–${SPECIES}. */
export function typesOf(id) {
  const at = (Number(id) - 1) * 2
  if (!(at >= 0 && at < CODES.length)) return []
  return [CODES[at], CODES[at + 1]]
    .filter((code) => code !== '.')
    .map((code) => TYPE_ORDER[LETTERS.indexOf(code)])
}
`
)
console.log(`wrote ${target} (${codes.length} chars)`)
