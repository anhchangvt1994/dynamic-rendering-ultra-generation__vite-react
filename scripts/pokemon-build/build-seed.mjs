// Builds supabase/seed/pokemon_build_v1.sql from public PokéAPI data: species
// base stats / abilities / growth / gender, the default form's learnset, the
// moves they reference and the TM / HM → move mapping of the Quiz catalogue.
//   node scripts/pokemon-build/build-seed.mjs [--cache DIR] [--output FILE]
// Downloaded data is parsed as JSON only, never executed. Any missing or
// malformed entry fails the whole build; no partial seed is ever written.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { ITEMS } from '../../src/pages/QuizPage/items.mjs'

export const TOTAL = 1025
const API = 'https://pokeapi.co/api/v2/'
const ROOT = fileURLToPath(new URL('../../', import.meta.url))
const STAT_ORDER = [
  'hp',
  'attack',
  'defense',
  'special-attack',
  'special-defense',
  'speed',
]
const GROWTH = {
  slow: 'slow',
  'medium-slow': 'medium-slow',
  medium: 'medium',
  fast: 'fast',
  'slow-then-very-fast': 'erratic',
  'fast-then-very-slow': 'fluctuating',
}
const METHODS = new Set(['level-up', 'machine', 'egg', 'tutor'])
const CHUNK = 500

const fail = (msg) => {
  throw new Error(`pokemon-build seed: ${msg}`)
}
const range = (n) => Array.from({ length: n }, (_, i) => i + 1)
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`
const num = (v) => (v === null || v === undefined ? 'null' : Number(v))

/** TM / HM items of the Quiz catalogue: [[itemId, moveSlug]] */
export const machinesOf = (items = ITEMS) =>
  items
    .filter((item) => item.move)
    .map((item) => [item.id, item.move.name.toLowerCase().replaceAll(' ', '-')])

/** One species' row and its learnset entries from the raw API payloads. */
export function parseSpecies(id, species, pokemon) {
  if (species?.id !== id || pokemon?.id !== id)
    fail(`species/pokemon ${id} id mismatch`)
  const stats = STAT_ORDER.map(
    (name) =>
      pokemon.stats?.find((s) => s.stat?.name === name)?.base_stat ??
      fail(`pokemon ${id} lacks stat ${name}`)
  )
  const growth =
    GROWTH[species.growth_rate?.name] ??
    fail(`species ${id} growth ${species.growth_rate?.name}`)
  const rate = species.gender_rate
  if (!Number.isInteger(rate) || rate < -1 || rate > 8)
    fail(`species ${id} gender_rate ${rate}`)
  const abilities = (pokemon.abilities ?? [])
    .map((a) => ({
      name: a.ability?.name ?? fail(`pokemon ${id} ability without a name`),
      hidden: a.is_hidden === true,
      slot: a.slot,
    }))
    .sort((a, b) => a.slot - b.slot)
  if (!abilities.some((a) => !a.hidden)) fail(`pokemon ${id} has no ability`)

  const learn = new Map()
  for (const m of pokemon.moves ?? []) {
    const move = m.move?.name ?? fail(`pokemon ${id} move without a name`)
    for (const d of m.version_group_details ?? []) {
      const method = d.move_learn_method?.name
      if (!METHODS.has(method)) continue
      const key = `${move}|${method}`
      let level = method === 'level-up' ? Math.max(1, d.level_learned_at) : 0
      if (learn.has(key)) level = Math.min(level, learn.get(key).level)
      learn.set(key, { move, method, level })
    }
  }
  if ((pokemon.moves ?? []).length && !learn.size)
    fail(`pokemon ${id} has moves but none of a known method`)
  return { id, stats, growth, rate, abilities, learn: [...learn.values()] }
}

const rows = (table, cols, tuples, tail) => {
  const out = []
  for (let i = 0; i < tuples.length; i += CHUNK)
    out.push(
      `insert into public.${table} (${cols}) values\n${tuples
        .slice(i, i + CHUNK)
        .map((t) => `  (${t})`)
        .join(',\n')}\n${tail};`
    )
  return out
}

/** The whole seed: data = { species: Map, pokemon: Map, moves: Map }. */
export function buildSeed(data, { ids = range(TOTAL), machines } = {}) {
  const parsed = [...ids]
    .sort((a, b) => a - b)
    .map((id) =>
      parseSpecies(
        id,
        data.species.get(id) ?? fail(`missing species ${id}`),
        data.pokemon.get(id) ?? fail(`missing pokemon ${id}`)
      )
    )
  const tms = machines ?? machinesOf()
  const wanted = new Set([
    ...parsed.flatMap((p) => p.learn.map((l) => l.move)),
    ...tms.map(([, move]) => move),
  ])
  const moves = [...wanted].sort().map((name) => {
    const m = data.moves.get(name) ?? fail(`missing move ${name}`)
    return [
      lit(name),
      lit(m.type?.name ?? fail(`move ${name} has no type`)),
      num(m.power),
      num(m.accuracy),
      num(m.pp),
      lit(m.damage_class?.name ?? fail(`move ${name} has no class`)),
    ].join(', ')
  })
  const sql = [
    '-- Generated by scripts/pokemon-build/build-seed.mjs. Do not edit.',
    'begin;',
    ...rows(
      'pokemon_species_base',
      'species, hp, atk, def, spa, spd, spe, growth, gender_rate, abilities',
      parsed.map(
        (p) =>
          `${p.id}, ${p.stats.join(', ')}, ${lit(p.growth)}, ${p.rate}, ${lit(JSON.stringify(p.abilities))}::jsonb`
      ),
      'on conflict (species) do update set hp = excluded.hp, atk = excluded.atk, def = excluded.def, spa = excluded.spa, spd = excluded.spd, spe = excluded.spe, growth = excluded.growth, gender_rate = excluded.gender_rate, abilities = excluded.abilities'
    ),
    ...rows(
      'pokemon_moves_ref',
      'move, type, power, accuracy, pp, damage_class',
      moves,
      'on conflict (move) do update set type = excluded.type, power = excluded.power, accuracy = excluded.accuracy, pp = excluded.pp, damage_class = excluded.damage_class'
    ),
    ...rows(
      'pokemon_learnset',
      'species, move, method, level',
      parsed.flatMap((p) =>
        p.learn
          .sort(
            (a, b) =>
              a.move.localeCompare(b.move) || a.method.localeCompare(b.method)
          )
          .map((l) => `${p.id}, ${lit(l.move)}, ${lit(l.method)}, ${l.level}`)
      ),
      'on conflict (species, move, method) do update set level = excluded.level'
    ),
    ...rows(
      'pokemon_machines',
      'item_id, move',
      tms.map(([item, move]) => `${lit(item)}, ${lit(move)}`),
      'on conflict (item_id) do update set move = excluded.move'
    ),
    'commit;',
    '',
  ].join('\n')
  return sql
}

async function getJson(url, cacheFile) {
  if (fs.existsSync(cacheFile))
    return JSON.parse(fs.readFileSync(cacheFile, 'utf8'))
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url)
      if (!res.ok) throw new Error(`HTTP ${res.status}`)
      const body = await res.text()
      const json = JSON.parse(body)
      fs.mkdirSync(path.dirname(cacheFile), { recursive: true })
      fs.writeFileSync(cacheFile, body)
      return json
    } catch (err) {
      if (attempt === 4) fail(`cannot fetch ${url}: ${err.message}`)
      await new Promise((r) => setTimeout(r, 500 * attempt))
    }
  }
}

async function pool(items, size, fn) {
  const out = new Map()
  let next = 0
  await Promise.all(
    Array.from({ length: size }, async () => {
      while (next < items.length) {
        const item = items[next++]
        out.set(item, await fn(item))
      }
    })
  )
  return out
}

export async function fetchAll(dir, ids = range(TOTAL)) {
  const get = (kind) => (key) =>
    getJson(`${API}${kind}/${key}`, path.join(dir, kind, `${key}.json`))
  const species = await pool(ids, 10, get('pokemon-species'))
  const pokemon = await pool(ids, 10, get('pokemon'))
  const names = new Set(machinesOf().map(([, move]) => move))
  for (const id of ids)
    for (const m of pokemon.get(id).moves ?? []) names.add(m.move.name)
  const moves = await pool([...names].sort(), 10, get('move'))
  return { species, pokemon, moves }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const arg = (flag, fallback) => {
    const i = process.argv.indexOf(flag)
    return i > 0 ? process.argv[i + 1] : fallback
  }
  const cache = arg('--cache', path.join(ROOT, '.superpowers/pokeapi-build'))
  const output = arg(
    '--output',
    path.join(ROOT, 'supabase/seed/pokemon_build_v1.sql')
  )
  const data = await fetchAll(cache)
  fs.writeFileSync(output, buildSeed(data))
  console.log(`wrote ${path.relative(ROOT, output)}`)
}
