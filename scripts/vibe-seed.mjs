// yarn vibe:seed [base]: asks a running server (default http://localhost:5190)
// for the vibe of every species and writes the seed migration that fills
// pokemon_species_vibes and re-derives every appearance. Re-run it when the
// vibe rule changes (bump its v), then `npx supabase migration up`.
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { VIBES } from '../src/pages/BagPage/individuals/palettes.mjs'

const OUT = 'supabase/migrations/20261117000100_pokemon_species_vibes_seed.sql'
const LAST = 1025
const CONCURRENCY = 6

const valid = (r) =>
  Number.isInteger(r?.id) &&
  r.id >= 1 &&
  r.id <= LAST &&
  VIBES.includes(r.vibe) &&
  Number.isInteger(r.v)

/** The migration text for these rows (sorted by species). */
export function seedSql(rows) {
  if (!rows.length) throw new Error('no rows')
  for (const r of rows) if (!valid(r)) throw new Error(`bad row ${JSON.stringify(r)}`)
  const values = [...rows]
    .sort((a, b) => a.id - b.id)
    .map((r) => `  (${r.id}, '${r.vibe}', ${r.v})`)
    .join(',\n')
  return [
    '-- Generated by `yarn vibe:seed` from GET /api/species-vibe/:id (the server',
    "-- rule in server/src/api/routes/vibe). Every species' vibe, then every",
    '-- individual takes the appearance its vibe gives.',
    'insert into public.pokemon_species_vibes (species_id, vibe, v) values',
    values,
    'on conflict (species_id) do update set vibe = excluded.vibe, v = excluded.v, updated_at = now();',
    '',
    'select public.pokemon_individuals_upgrade_appearance();',
    '',
  ].join('\n')
}

async function vibeOf(base, id) {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(`${base}/api/species-vibe/${id}`)
      if (res.ok) {
        const body = await res.json()
        return { id: body.id, vibe: body.vibe, v: body.v }
      }
      if (attempt >= 3) throw new Error(`species ${id}: HTTP ${res.status}`)
    } catch (e) {
      if (attempt >= 3) throw e
    }
    await new Promise((r) => setTimeout(r, 500 * attempt))
  }
}

async function main() {
  const base = (process.argv[2] || 'http://localhost:5190').replace(/\/+$/, '')
  const rows = []
  let next = 1
  await Promise.all(
    Array.from({ length: CONCURRENCY }, async () => {
      while (next <= LAST) {
        const id = next++
        rows.push(await vibeOf(base, id))
        if (rows.length % 100 === 0) console.log(`${rows.length}/${LAST}`)
      }
    })
  )
  await writeFile(OUT, seedSql(rows))
  const counts = Object.fromEntries(VIBES.map((v) => [v, 0]))
  for (const r of rows) counts[r.vibe]++
  console.log(`wrote ${OUT}`, counts)
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  main().catch((e) => {
    console.error(e.message)
    process.exit(1)
  })
