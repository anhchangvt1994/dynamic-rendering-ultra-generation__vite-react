const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

export const GYMS = Object.entries(ROWS).flatMap(([region, rows]) =>
  rows.map(([leader, town, type, badge, kind]) => ({
    id: `${region}-${slug(leader)}${kind === 'champion' ? '-champion' : ''}`,
    region,
    town,
    leader,
    type,
    badge,
    kind,
  }))
)

export const gymsOf = (regionId) => GYMS.filter((g) => g.region === regionId)

/** The town's own gym or kahuna, if it has one. */
export const gymOfTown = (regionId, town) =>
  GYMS.find((g) => g.region === regionId && g.town === town && (g.kind === 'gym' || g.kind === 'kahuna'))
